<?php

use App\Models\User;
use App\Services\Security\TwoFactorAuthService;
use Illuminate\Foundation\Testing\RefreshDatabase;
use PragmaRX\Google2FA\Google2FA;

uses(RefreshDatabase::class);

test('fix 1: 2fa strict rfc 6238 totp validation rejects 123456 backdoor and accepts valid otp', function () {
    $user = User::factory()->create(['email' => 'admin@larashop.test']);
    $service = app(TwoFactorAuthService::class);

    $setup = $service->enable2FA($user);
    $secret = $setup['secret'];

    $google2fa = new Google2FA;
    $validCurrentOtp = $google2fa->getCurrentOtp($secret);

    // 1. Valid RFC 6238 TOTP code generated by Google2FA MUST be accepted
    expect($service->verifyCode($user->fresh(), $validCurrentOtp))->toBeTrue();

    // 2. Hardcoded '123456' backdoor MUST be strictly rejected
    if ($validCurrentOtp !== '123456') {
        expect($service->verifyCode($user->fresh(), '123456'))->toBeFalse();
    }

    // 3. Arbitrary invalid OTP code MUST be rejected
    expect($service->verifyCode($user->fresh(), '000000'))->toBeFalse();
});
